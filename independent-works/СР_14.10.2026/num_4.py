weight = round(float(input('Введите свой вес (точное значение до 68 кг влючительно), для определения весовой категории: ')))

if 64 <= weight < 69 :
    print('Вы будете выступать в полусредней весовой категории')

elif 60 <= weight < 64:
    print('Вы будете выступать в первой полусредней весовой категории')

else:
    print('Вы будете выступать в лёгкой весовой категории')