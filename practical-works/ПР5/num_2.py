weight ,height = map(float, input("Введите свой вес(кг) и рост(м) через пробел для рассчета ИМТ: ").split(' ')) # Пользователь вводит данные массы и роста в одну строку через пробел

bmi_calc = weight / (height**2) # Рассчёт ИМТ

print(f'Ваш ИМТ составляет: {bmi_calc:.1f}') #Вывод рассчитанного ИМТ